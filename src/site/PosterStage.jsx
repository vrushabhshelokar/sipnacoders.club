// The poster slot used by all 10 popups and all 5 Upcoming cards.
//
// No poster in src/assets/upcoming/  ->  this renders exactly what it is given (the "?", radar, rocket ... as always).
// A poster is there                  ->  the mystery picture stays for 2 seconds, then a crazy reveal plays (slam, curtain, flip, iris, assemble,
//                                        spotlight, scroll, zap, burst or warp: each design has its own, see site/designs.js) and the poster stays.
//                                        (It does not wait for "Try to decrypt".)
// Several posters (hackathon, hackathon1, hackathon2 ...) -> a slideshow. On the Upcoming card there are arrows, dots, swipe,
// and a tap opens the poster full size so people can read it.
//
// You do not edit this file. Name your poster files like src/assets/upcoming/README.txt says.
import { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import { createPortal } from 'react-dom';
import { Icon } from './Icons';
import { POSTERS, HAS_POSTERS } from './posters';
import { getFx } from './teaserCore';
import './PosterStage.css';

export { HAS_POSTERS };

const HOLD = 2000;     // how long the mystery picture stays before the poster is revealed (ms)
const REVEAL = 1700;   // the reveal itself (ms)
const SLIDE = 4600;    // time for each poster when there are several (ms)
const L = POSTERS.length;

const reduced = () => !!(window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches);
const RATIO = new Map();   // width / height of every poster that has loaded (each one is shown in its own true shape)
const loadRatio = (url) => new Promise((ok, bad) => {
  const im = new Image();
  im.onload = () => { const r = im.naturalWidth / (im.naturalHeight || 1); RATIO.set(url, r); ok(r); };
  im.onerror = bad;
  im.src = url;
});
const wrap = (n) => ((n % L) + L) % L;
const rnd = (k, s = 1) => { const x = Math.sin((k + 1) * 12.9898 + s * 78.233) * 43758.5453; return x - Math.floor(x); };   // the same "random" numbers every time
const range = (n) => Array.from({ length: n }, (_, k) => k);

/* the extra pieces some reveals draw on top (curtains, rings, confetti ...). The look is in PosterStage.css */
const CONFETTI = ['#ff4fd8', '#ffd23f', '#2de2e6', '#7cff6b', '#ff5a5a', '#ffffff', '#8a7bff'];
function Fx({ name }) {
  if (name === 'curtain') return <div className="ps-fx" aria-hidden="true"><i /><i /><i /></div>;
  if (name === 'slam' || name === 'iris') return <div className="ps-fx" aria-hidden="true"><i /><i /><i /></div>;
  if (name === 'flip' || name === 'scroll' || name === 'spotlight' || name === 'assemble') return <div className="ps-fx" aria-hidden="true"><i /></div>;
  if (name === 'zap') {
    return (
      <div className="ps-fx" aria-hidden="true">
        <i />
        <svg viewBox="0 0 100 100" preserveAspectRatio="none">
          <polyline points="62,0 48,22 58,24 38,50 50,52 30,100" />
          <polyline points="20,0 34,26 24,30 52,58 42,62 70,100" />
          <polyline points="82,0 66,20 74,24 46,48 56,52 22,100" />
        </svg>
      </div>
    );
  }
  if (name === 'burst') {
    return (
      <div className="ps-fx" aria-hidden="true">
        {range(30).map((k) => {
          const a = (k / 30) * Math.PI * 2 + rnd(k, 3) * 0.5, d = 80 + rnd(k, 5) * 130;
          return (
            <i
              key={k}
              style={{
                '--dx': `${Math.round(Math.cos(a) * d)}px`, '--dy': `${Math.round(Math.sin(a) * d * 0.8 - 30)}px`, '--rot': `${Math.round((rnd(k, 7) - 0.5) * 900)}deg`,
                '--c': CONFETTI[k % CONFETTI.length], '--w': `${6 + Math.round(rnd(k, 9) * 7)}px`, '--h': `${9 + Math.round(rnd(k, 11) * 9)}px`, '--d': `${Math.round(rnd(k, 13) * 110)}ms`,
                borderRadius: k % 3 === 0 ? '50%' : '2px',
              }}
            />
          );
        })}
      </div>
    );
  }
  if (name === 'warp') {
    return (
      <div className="ps-fx" aria-hidden="true">
        {range(22).map((k) => <i key={k} style={{ '--a': `${Math.round((k / 22) * 360 + rnd(k, 2) * 12)}deg`, '--d': `${Math.round(rnd(k, 4) * 260)}ms`, '--l': `${52 + Math.round(rnd(k, 6) * 40)}%` }} />)}
        <b />
      </div>
    );
  }
  return null;
}

/* "assemble": the poster arrives in pieces (4 x 5). Each piece is the real poster, cut with clip-path, flying in from a random place. */
const COLS = 4, ROWS = 5;
function Tiles({ url, r }) {
  return (
    <div className="ps-tiles" aria-hidden="true">
      {range(COLS * ROWS).map((k) => {
        const c = k % COLS, rw = Math.floor(k / COLS);
        const ang = rnd(k, 21) * Math.PI * 2, far = 90 + rnd(k, 23) * 90;
        return (
          <div
            key={k}
            className="ps-tile"
            style={{
              clipPath: `inset(${(rw / ROWS) * 100}% ${((COLS - c - 1) / COLS) * 100}% ${((ROWS - rw - 1) / ROWS) * 100}% ${(c / COLS) * 100}%)`,
              '--tx': `${Math.round(Math.cos(ang) * far)}%`, '--ty': `${Math.round(Math.sin(ang) * far)}%`, '--tr': `${Math.round((rnd(k, 25) - 0.5) * 420)}deg`,
              '--d': `${120 + ((k * 7) % (COLS * ROWS)) * 32}ms`,
            }}
          >
            <figure className="ps-slide" style={{ '--r': r }}><img src={url} alt="" draggable="false" /></figure>
          </div>
        );
      })}
    </div>
  );
}

/* the poster in full size (cards only) */
function Lightbox({ index, onIndex, onClose }) {
  const box = useRef(null);
  const idx = useRef(index);
  const swipe = useRef(null);
  idx.current = index;

  useEffect(() => {
    const before = document.activeElement;
    const html = document.documentElement;
    const oldOverflow = html.style.overflow;
    html.style.overflow = 'hidden';
    const first = box.current && box.current.querySelector('button');
    if (first) first.focus({ preventScroll: true });
    const onKey = (e) => {
      if (e.key === 'Escape') { e.preventDefault(); e.stopPropagation(); onClose(); }
      else if (e.key === 'ArrowRight') onIndex(wrap(idx.current + 1));
      else if (e.key === 'ArrowLeft') onIndex(wrap(idx.current - 1));
      else if (e.key === 'Tab' && box.current) {
        const items = [...box.current.querySelectorAll('button')];
        if (!items.length) return;
        const a = items[0], z = items[items.length - 1];
        if (e.shiftKey && document.activeElement === a) { e.preventDefault(); z.focus(); }
        else if (!e.shiftKey && document.activeElement === z) { e.preventDefault(); a.focus(); }
      }
    };
    document.addEventListener('keydown', onKey, true);
    return () => {
      document.removeEventListener('keydown', onKey, true);
      html.style.overflow = oldOverflow;
      if (before && before.focus && document.contains(before)) before.focus({ preventScroll: true });
    };
  }, [onClose, onIndex]);

  return createPortal(
    <div
      ref={box}
      className="ps-lb"
      role="dialog"
      aria-modal="true"
      aria-label="Event poster"
      onClick={(e) => { if (e.target === e.currentTarget) onClose(); }}
      onPointerDown={(e) => { swipe.current = e.clientX; }}
      onPointerUp={(e) => {
        const x = swipe.current; swipe.current = null;
        if (x === null || L < 2) return;
        const dx = e.clientX - x;
        if (Math.abs(dx) > 50) onIndex(wrap(index + (dx < 0 ? 1 : -1)));
      }}
    >
      <button type="button" className="ps-lb-x" onClick={onClose} aria-label="Close poster"><Icon.X size={20} /></button>
      <img className="ps-lb-img" src={POSTERS[index]} alt={`Event poster ${index + 1} of ${L}`} draggable="false" />
      {L > 1 && (
        <>
          <button type="button" className="ps-lb-nav is-prev" onClick={() => onIndex(wrap(index - 1))} aria-label="Previous poster"><Icon.ChevronLeft size={22} /></button>
          <button type="button" className="ps-lb-nav is-next" onClick={() => onIndex(wrap(index + 1))} aria-label="Next poster"><Icon.ChevronRight size={22} /></button>
          <span className="ps-lb-count" aria-hidden="true">{index + 1} / {L}</span>
        </>
      )}
    </div>,
    document.body,
  );
}

function Stage({ children, kind, cap, className, frameW, frameH }) {
  const root = useRef(null);
  const cur = useRef(0);
  const down = useRef(null);
  const swiped = useRef(false);
  const [ratio, setRatio] = useState(0);        // 0 = the first poster has not loaded yet
  const [bad, setBad] = useState(false);
  const [seen, setSeen] = useState(false);
  const [phase, setPhase] = useState('wait');   // wait -> reveal -> poster
  const fx = useMemo(() => getFx(), []);        // which reveal this design uses
  const [h, setH] = useState(0);
  const [i, setI] = useState(0);
  const [prev, setPrev] = useState(-1);
  const [moved, setMoved] = useState(false);
  const [hold, setHold] = useState(false);      // a finger / mouse is on it: stop the slideshow
  const [box, setBox] = useState(false);        // full size view
  const [, setTick] = useState(0);              // a poster finished loading: draw it in its own shape
  const many = L > 1;
  const isCard = kind === 'card';

  // load the first poster
  useEffect(() => {
    let dead = false;
    loadRatio(POSTERS[0]).then((r) => { if (!dead) setRatio(r); }).catch(() => { if (!dead) setBad(true); });
    return () => { dead = true; };
  }, []);

  // wait until it is on screen
  useEffect(() => {
    const el = root.current;
    if (!el) return undefined;
    if (!('IntersectionObserver' in window)) { setSeen(true); return undefined; }
    const io = new IntersectionObserver((es) => { if (es.some((e) => e.isIntersecting)) { setSeen(true); io.disconnect(); } }, { threshold: 0.3 });
    io.observe(el);
    return () => io.disconnect();
  }, []);

  // how tall the poster should be at this width (so the whole poster is visible)
  const fit = useCallback(() => {
    const el = root.current;
    if (!el || !ratio) return;
    const vh = window.innerHeight || 800;
    const tall = vh > (window.innerWidth || 400);   // portrait phone / desktop
    const popupTop = !tall ? vh * 0.42 : vh < 700 ? vh * 0.27 : vh < 800 ? vh * 0.3 : Math.min(vh * 0.4, 340);   // small screens: keep the whole popup on screen
    const top = cap || (kind === 'popup' ? popupTop : Math.min(vh * 0.78, 620));
    // --ps-s (PosterStage.css) = how much a tilted poster sticks out at its corners; the poster is made a little smaller so no corner is cut
    const k = parseFloat(getComputedStyle(el).getPropertyValue('--ps-s')) || 0;
    const inner = Math.max(40, el.clientWidth - frameW) / (1 + k / ratio);   // a framed poster (the Dossier photo) has a border around the picture
    setH(Math.round(Math.min(inner * (k + 1 / ratio) + frameH, top)));
  }, [ratio, cap, kind, frameW, frameH]);

  // mystery picture (2 s) -> reveal -> poster
  useEffect(() => {
    if (phase !== 'wait' || !ratio || !seen) return undefined;
    const quick = reduced();
    const t = setTimeout(() => { fit(); setPhase(quick ? 'poster' : 'reveal'); }, quick ? 0 : HOLD);
    return () => clearTimeout(t);
  }, [phase, ratio, seen, fit]);
  useEffect(() => {
    if (phase !== 'reveal') return undefined;
    const t = setTimeout(() => setPhase('poster'), REVEAL);
    return () => clearTimeout(t);
  }, [phase]);
  useEffect(() => {
    if (phase === 'wait') return undefined;
    const el = root.current;
    let ro = null;
    window.addEventListener('resize', fit);
    if (el && 'ResizeObserver' in window) { ro = new ResizeObserver(fit); ro.observe(el); }
    return () => { window.removeEventListener('resize', fit); if (ro) ro.disconnect(); };
  }, [phase, fit]);

  const go = useCallback((n) => {
    const next = wrap(n);
    if (next === cur.current) return;
    setPrev(cur.current);
    cur.current = next;
    setMoved(true);
    setI(next);
  }, []);

  // slideshow
  useEffect(() => {
    if (phase !== 'poster' || !many || hold || box || reduced()) return undefined;
    const t = setTimeout(() => go(cur.current + 1), SLIDE);
    return () => clearTimeout(t);
  }, [phase, many, hold, box, i, go]);
  useEffect(() => {
    if (phase === 'wait' || !many) return;
    loadRatio(POSTERS[wrap(i + 1)]).then(() => setTick((t) => t + 1)).catch(() => { /* a broken one is skipped when its turn comes */ });
  }, [phase, many, i]);

  if (bad) return <>{children}</>;   // the poster file is broken: keep the mystery picture

  const slides = [prev, i].filter((n, k, a) => n >= 0 && a.indexOf(n) === k);
  const onPoster = phase === 'reveal' || phase === 'poster';

  return (
    <div ref={root} className={`ps ps-${kind} is-${phase} fx-${fx} ${className || ''}`} style={{ '--ps-h': `${h}px` }}>
      <div className="ps-mystery" aria-hidden="true">{children}</div>

      {onPoster && (
        <div
          className="ps-poster"
          role={isCard && many ? 'group' : undefined}
          aria-roledescription={isCard && many ? 'carousel' : undefined}
          aria-label={isCard && many ? 'Event posters' : undefined}
          onPointerEnter={isCard ? () => setHold(true) : undefined}
          onPointerLeave={isCard ? () => setHold(false) : undefined}
          onFocus={isCard ? () => setHold(true) : undefined}
          onBlur={isCard ? () => setHold(false) : undefined}
          onKeyDown={isCard && many ? (e) => {
            if (e.key === 'ArrowRight') { e.preventDefault(); go(cur.current + 1); }
            else if (e.key === 'ArrowLeft') { e.preventDefault(); go(cur.current - 1); }
          } : undefined}
        >
          {slides.map((n) => (
            <figure key={n} className={`ps-slide ${n === i ? 'is-on' : 'is-off'} ${moved ? 'is-fade' : ''}`} style={{ '--r': RATIO.get(POSTERS[n]) || ratio || 0.8 }}>
              <span className="ps-blur" style={{ backgroundImage: `url("${POSTERS[n]}")` }} aria-hidden="true" />
              <img
                src={POSTERS[n]}
                alt={`Event poster${many ? ` ${n + 1} of ${L}` : ''}`}
                draggable="false"
                decoding="async"
                onLoad={(e) => { const im = e.currentTarget; const r = im.naturalWidth / (im.naturalHeight || 1); if (RATIO.get(POSTERS[n]) !== r) { RATIO.set(POSTERS[n], r); setTick((t) => t + 1); } }}
              />
            </figure>
          ))}

          {phase === 'reveal' && fx === 'assemble' && <Tiles url={POSTERS[i]} r={RATIO.get(POSTERS[i]) || ratio || 0.8} />}

          {isCard && phase === 'poster' && (
            <button
              type="button"
              className="ps-hit"
              aria-label="Open the poster full size"
              onPointerDown={(e) => { down.current = e.clientX; swiped.current = false; }}
              onPointerUp={(e) => {
                const x = down.current; down.current = null;
                if (x === null || !many) return;
                const dx = e.clientX - x;
                if (Math.abs(dx) > 40) { swiped.current = true; go(cur.current + (dx < 0 ? 1 : -1)); }
              }}
              onClick={() => { if (swiped.current) { swiped.current = false; return; } setBox(true); }}
            >
              <span className="ps-zoom"><Icon.Search size={14} /> Tap to enlarge</span>
            </button>
          )}

          {isCard && phase === 'poster' && many && (
            <>
              <button type="button" className="ps-nav is-prev" onClick={() => go(cur.current - 1)} aria-label="Previous poster"><Icon.ChevronLeft size={20} /></button>
              <button type="button" className="ps-nav is-next" onClick={() => go(cur.current + 1)} aria-label="Next poster"><Icon.ChevronRight size={20} /></button>
              <div className="ps-dots">
                {POSTERS.map((_, n) => (
                  <button key={n} type="button" className={n === i ? 'is-on' : ''} onClick={() => go(n)} aria-label={`Show poster ${n + 1}`} aria-current={n === i ? 'true' : undefined} />
                ))}
              </div>
            </>
          )}
        </div>
      )}

      {phase === 'reveal' && <Fx name={fx} />}

      {box && <Lightbox index={i} onIndex={go} onClose={() => setBox(false)} />}
    </div>
  );
}

/* Wrap the mystery picture of a popup / card in this.
   kind: 'popup' | 'card'   cap: tallest the poster may get (px, optional)
   onlyWithPoster: the children are only a stand-in for the poster (the Terminal card): nothing is drawn without a poster
   frameW / frameH: room the design keeps around the picture (px): the poster is shown a little smaller, like a print
                    with a margin (--ps-pad in PosterStage.css is half of this) */
export default function PosterStage({ children, kind = 'card', cap, className, onlyWithPoster = false, frameW = 28, frameH = 28 }) {
  if (!HAS_POSTERS) return onlyWithPoster ? null : <>{children}</>;
  return <Stage kind={kind} cap={cap} className={className} frameW={frameW} frameH={frameH}>{children}</Stage>;
}
